-- 1.1 INVOICE SUMMARY
CREATE OR REPLACE VIEW KF_VW_INVOICE_SUMMARY AS
SELECT 
    i.INVOICE_ID,
    i.INVOICE_NUMBER,
    i.VENDOR_ID,
    v.VENDOR_NAME,
    i.FISCAL_YEAR_ID,
    f.FISCAL_YEAR_CODE,
    i.INVOICE_DATE,
    i.DUE_DATE,
    i.CURRENCY AS CURRENCY_CODE,
    i.SUBTOTAL,
    i.TAX_AMOUNT,
    i.TDS_AMOUNT,
    i.TOTAL_AMOUNT,
    i.STATUS,
    i.SOURCE_TYPE AS SOURCE,
    i.CREATED_DATE AS CREATED_AT,
    i.UPDATED_DATE AS UPDATED_AT
FROM KF_INVOICES i
JOIN KF_VENDORS v ON i.VENDOR_ID = v.VENDOR_ID
LEFT JOIN KF_FISCAL_YEARS f ON i.FISCAL_YEAR_ID = f.FISCAL_YEAR_ID;

-- 1.2 INVOICE BALANCES
CREATE OR REPLACE VIEW KF_VW_INVOICE_BALANCES AS
SELECT 
    i.INVOICE_ID,
    i.INVOICE_NUMBER,
    v.VENDOR_NAME,
    i.TOTAL_AMOUNT,
    NVL(p.TOTAL_PAID, 0) AS TOTAL_PAID,
    (i.TOTAL_AMOUNT - NVL(p.TOTAL_PAID, 0)) AS BALANCE_AMOUNT,
    CASE 
        WHEN i.STATUS IN ('DRAFT', 'REJECTED', 'CANCELLED', 'PENDING_APPROVAL', 'OVERDUE') THEN i.STATUS
        WHEN NVL(p.TOTAL_PAID, 0) = 0 THEN 'UNPAID'
        WHEN NVL(p.TOTAL_PAID, 0) > 0 AND NVL(p.TOTAL_PAID, 0) < i.TOTAL_AMOUNT THEN 'PARTIALLY_PAID'
        WHEN NVL(p.TOTAL_PAID, 0) >= i.TOTAL_AMOUNT THEN 'PAID'
    END AS PAYMENT_STATUS
FROM KF_INVOICES i
JOIN KF_VENDORS v ON i.VENDOR_ID = v.VENDOR_ID
LEFT JOIN (
    SELECT INVOICE_ID, SUM(PAYMENT_AMOUNT) AS TOTAL_PAID
    FROM KF_PAYMENTS
    WHERE STATUS = 'COMPLETED'
    GROUP BY INVOICE_ID
) p ON i.INVOICE_ID = p.INVOICE_ID;

-- 1.3 PAYMENT SUMMARY
CREATE OR REPLACE VIEW KF_VW_PAYMENT_SUMMARY AS
SELECT 
    p.PAYMENT_ID,
    p.INVOICE_ID,
    i.INVOICE_NUMBER,
    p.VENDOR_ID,
    v.VENDOR_NAME,
    p.PAYMENT_DATE,
    p.PAYMENT_AMOUNT,
    p.PAYMENT_METHOD,
    p.REFERENCE_NUMBER,
    p.STATUS,
    p.CREATED_DATE AS CREATED_AT
FROM KF_PAYMENTS p
JOIN KF_INVOICES i ON p.INVOICE_ID = i.INVOICE_ID
JOIN KF_VENDORS v ON p.VENDOR_ID = v.VENDOR_ID;

-- 1.4 PENDING APPROVALS
CREATE OR REPLACE VIEW KF_VW_PENDING_APPROVALS AS
SELECT 
    a.APPROVAL_ID AS APPROVAL_REQUEST_ID,
    a.ENTITY_TYPE,
    a.ENTITY_ID,
    a.REQUESTED_BY,
    a.REQUESTED_DATE AS REQUESTED_AT,
    a.STATUS,
    a.ASSIGNED_APPROVER,
    a.DECISION_DATE,
    a.COMMENTS
FROM KF_APPROVAL_REQUESTS a
WHERE a.STATUS = 'PENDING';

-- 1.5 CASH FLOW MONTHLY
CREATE OR REPLACE VIEW KF_VW_CASH_FLOW_MONTHLY AS
SELECT 
    t.FISCAL_YEAR_ID,
    TO_CHAR(e.TRANSACTION_DATE, 'YYYY') AS YEAR,
    TO_CHAR(e.TRANSACTION_DATE, 'MM') AS MONTH,
    TO_CHAR(e.TRANSACTION_DATE, 'Mon') AS MONTH_NAME,
    SUM(CASE WHEN e.TRANSACTION_TYPE = 'INFLOW' THEN e.AMOUNT ELSE 0 END) AS INFLOW,
    SUM(CASE WHEN e.TRANSACTION_TYPE = 'OUTFLOW' THEN e.AMOUNT ELSE 0 END) AS OUTFLOW,
    SUM(CASE WHEN e.TRANSACTION_TYPE = 'INFLOW' THEN e.AMOUNT ELSE 0 END) - 
    SUM(CASE WHEN e.TRANSACTION_TYPE = 'OUTFLOW' THEN e.AMOUNT ELSE 0 END) AS NET_CASH_FLOW
FROM KF_CASH_FLOW_ENTRIES e
JOIN KF_CASH_FLOW_TRACKERS t ON e.TRACKER_ID = t.TRACKER_ID
WHERE e.STATUS = 'ACTIVE' AND t.STATUS = 'APPROVED'
GROUP BY t.FISCAL_YEAR_ID, TO_CHAR(e.TRANSACTION_DATE, 'YYYY'), TO_CHAR(e.TRANSACTION_DATE, 'MM'), TO_CHAR(e.TRANSACTION_DATE, 'Mon');

-- 1.6 TDS SUMMARY
CREATE OR REPLACE VIEW KF_VW_TDS_SUMMARY AS
SELECT 
    t.TDS_SECTION,
    SUM(t.TAXABLE_AMOUNT) AS TOTAL_TAXABLE_AMOUNT,
    SUM(t.TDS_AMOUNT) AS TOTAL_TDS,
    SUM(CASE WHEN t.STATUS = 'PENDING' THEN t.TDS_AMOUNT ELSE 0 END) AS PENDING_TDS,
    SUM(CASE WHEN t.STATUS = 'DEPOSITED' THEN t.TDS_AMOUNT ELSE 0 END) AS DEPOSITED_TDS
FROM KF_TDS_TRANSACTIONS t
GROUP BY t.TDS_SECTION;

-- 1.7 VENDOR SUMMARY
CREATE OR REPLACE VIEW KF_VW_VENDOR_SUMMARY AS
SELECT 
    v.VENDOR_ID,
    v.VENDOR_CODE,
    v.VENDOR_NAME,
    COUNT(i.INVOICE_ID) AS TOTAL_INVOICES,
    NVL(SUM(i.TOTAL_AMOUNT), 0) AS TOTAL_INVOICE_VALUE,
    NVL(SUM(b.TOTAL_PAID), 0) AS TOTAL_PAID,
    NVL(SUM(b.BALANCE_AMOUNT), 0) AS OUTSTANDING_AMOUNT,
    NVL(SUM(CASE WHEN i.DUE_DATE < SYSDATE AND b.BALANCE_AMOUNT > 0 THEN b.BALANCE_AMOUNT ELSE 0 END), 0) AS OVERDUE_AMOUNT
FROM KF_VENDORS v
LEFT JOIN KF_INVOICES i ON v.VENDOR_ID = i.VENDOR_ID AND i.STATUS != 'CANCELLED'
LEFT JOIN KF_VW_INVOICE_BALANCES b ON i.INVOICE_ID = b.INVOICE_ID
GROUP BY v.VENDOR_ID, v.VENDOR_CODE, v.VENDOR_NAME;

-- 1.8 DASHBOARD KPIS
CREATE OR REPLACE VIEW KF_VW_DASHBOARD_KPIS AS
SELECT
    (SELECT COUNT(*) FROM KF_INVOICES WHERE STATUS != 'CANCELLED') AS TOTAL_INVOICES,
    (SELECT COUNT(*) FROM KF_APPROVAL_REQUESTS WHERE STATUS = 'PENDING') AS PENDING_APPROVALS,
    (SELECT NVL(SUM(TOTAL_AMOUNT), 0) FROM KF_INVOICES WHERE STATUS != 'CANCELLED') AS TOTAL_INVOICE_VALUE,
    (SELECT NVL(SUM(PAYMENT_AMOUNT), 0) FROM KF_PAYMENTS WHERE STATUS = 'COMPLETED') AS TOTAL_PAID,
    (SELECT NVL(SUM(BALANCE_AMOUNT), 0) FROM KF_VW_INVOICE_BALANCES WHERE PAYMENT_STATUS IN ('UNPAID', 'PARTIALLY_PAID', 'OVERDUE')) AS TOTAL_OUTSTANDING,
    (SELECT COUNT(*) FROM KF_VENDORS WHERE STATUS = 'ACTIVE') AS TOTAL_VENDORS,
    (SELECT NVL(SUM(TDS_AMOUNT), 0) FROM KF_TDS_TRANSACTIONS WHERE STATUS = 'PENDING') AS TOTAL_TDS
FROM DUAL;


