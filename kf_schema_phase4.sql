CREATE OR REPLACE PACKAGE BODY KF_PKG_CASH_FLOW AS
    PROCEDURE VALIDATE_TRACKER (P_TRACKER_ID IN NUMBER) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM KF_CASH_FLOW_ENTRIES WHERE TRACKER_ID = P_TRACKER_ID;
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20050, 'Tracker has no entries.');
        END IF;
    END VALIDATE_TRACKER;

    PROCEDURE SUBMIT_FOR_APPROVAL (P_TRACKER_ID IN NUMBER, P_REQUESTED_BY_USER_ID IN NUMBER) IS
        v_username VARCHAR2(100);
        v_status VARCHAR2(50);
    BEGIN
        SELECT STATUS INTO v_status FROM KF_CASH_FLOW_TRACKERS WHERE TRACKER_ID = P_TRACKER_ID FOR UPDATE;
        IF v_status != 'DRAFT' THEN
            RAISE_APPLICATION_ERROR(-20051, 'Only DRAFT trackers can be submitted.');
        END IF;
        
        VALIDATE_TRACKER(P_TRACKER_ID);
        SELECT USERNAME INTO v_username FROM KF_USERS WHERE USER_ID = P_REQUESTED_BY_USER_ID;
        
        UPDATE KF_CASH_FLOW_TRACKERS SET STATUS = 'PENDING_APPROVAL' WHERE TRACKER_ID = P_TRACKER_ID;
        
        KF_PKG_APPROVAL.SUBMIT_APPROVAL(
            P_ENTITY_TYPE => 'CASH_FLOW',
            P_ENTITY_ID => P_TRACKER_ID,
            P_REQUESTED_BY => v_username
        );
        KF_PKG_AUDIT.LOG_EVENT(P_REQUESTED_BY_USER_ID, 'UPDATE', 'KF_CASH_FLOW_TRACKERS', TO_CHAR(P_TRACKER_ID));
    END SUBMIT_FOR_APPROVAL;
END KF_PKG_CASH_FLOW;
