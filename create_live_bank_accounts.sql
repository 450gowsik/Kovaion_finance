BEGIN
    -- 1. Safely drop existing banking tables if they exist
    FOR t IN (
        SELECT table_name FROM user_tables 
        WHERE table_name IN ('KF_BANK_TRANSACTIONS', 'KF_BANK_ACCOUNTS')
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;

    -- 2. Create KF_BANK_ACCOUNTS Master Table
    EXECUTE IMMEDIATE '
    CREATE TABLE KF_BANK_ACCOUNTS (
        ACCOUNT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ACCOUNT_NUMBER VARCHAR2(35) NOT NULL UNIQUE,
        BANK_NAME VARCHAR2(100) NOT NULL,
        ACCOUNT_TYPE VARCHAR2(50) DEFAULT ''CURRENT'',
        IFSC_CODE VARCHAR2(20),
        BRANCH_NAME VARCHAR2(100),
        CURRENCY VARCHAR2(10) DEFAULT ''INR'',
        OPENING_BALANCE NUMBER(15,2) DEFAULT 0,
        CURRENT_BALANCE NUMBER(15,2) DEFAULT 0,
        RECONCILED_BALANCE NUMBER(15,2) DEFAULT 0,
        LAST_RECONCILED_DATE DATE DEFAULT SYSDATE,
        IS_ACTIVE VARCHAR2(1) DEFAULT ''Y'',
        CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
    )';

    -- 3. Create KF_BANK_TRANSACTIONS Ledger Table
    EXECUTE IMMEDIATE '
    CREATE TABLE KF_BANK_TRANSACTIONS (
        TRANSACTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ACCOUNT_ID NUMBER REFERENCES KF_BANK_ACCOUNTS(ACCOUNT_ID),
        TRANSACTION_DATE DATE NOT NULL,
        VALUE_DATE DATE,
        TRANSACTION_TYPE VARCHAR2(10) NOT NULL,
        AMOUNT NUMBER(15,2) NOT NULL,
        RUNNING_BALANCE NUMBER(15,2),
        REFERENCE_NUMBER VARCHAR2(100),
        DESCRIPTION VARCHAR2(255),
        COUNTERPARTY_NAME VARCHAR2(150),
        CATEGORY VARCHAR2(50),
        RECONCILIATION_STATUS VARCHAR2(30) DEFAULT ''RECONCILED'',
        RECONCILED_DATE DATE DEFAULT SYSDATE,
        CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
    )';

    -- 4. Seed 3 Active Corporate Bank Accounts with Live Reconciled Balances
    -- Deducts any completed vendor disbursements from HDFC operating account
    EXECUTE IMMEDIATE q'[
    INSERT INTO KF_BANK_ACCOUNTS (
        ACCOUNT_NUMBER, BANK_NAME, ACCOUNT_TYPE, IFSC_CODE, BRANCH_NAME,
        OPENING_BALANCE, CURRENT_BALANCE, RECONCILED_BALANCE, LAST_RECONCILED_DATE, IS_ACTIVE
    )
    SELECT '982145001234', 'HDFC Bank Ltd.', 'Corporate Current', 'HDFC0000123', 'Koramangala, Bengaluru', 
           8245000, 
           8245000 - (SELECT NVL(SUM(PAYMENT_AMOUNT), 0) FROM KF_PAYMENTS WHERE STATUS = 'COMPLETED'), 
           8245000 - (SELECT NVL(SUM(PAYMENT_AMOUNT), 0) FROM KF_PAYMENTS WHERE STATUS = 'COMPLETED'), 
           SYSDATE, 'Y' FROM dual UNION ALL
    SELECT '412089005678', 'ICICI Bank Ltd.', 'Operating Current', 'ICIC0000456', 'BKC, Mumbai', 
           3472680, 3472680, 3472680, SYSDATE, 'Y' FROM dual UNION ALL
    SELECT '105432007890', 'State Bank of India', 'Statutory Reserves', 'SBIN0000800', 'Connaught Place, New Delhi', 
           1050000, 1050000, 1050000, SYSDATE, 'Y' FROM dual
    ]';

    -- 5. Seed Real Bank Statement Transactions
    EXECUTE IMMEDIATE q'[
    INSERT INTO KF_BANK_TRANSACTIONS (
        ACCOUNT_ID, TRANSACTION_DATE, VALUE_DATE, TRANSACTION_TYPE, AMOUNT,
        REFERENCE_NUMBER, DESCRIPTION, COUNTERPARTY_NAME, CATEGORY, RECONCILIATION_STATUS, RECONCILED_DATE
    )
    SELECT (SELECT ACCOUNT_ID FROM KF_BANK_ACCOUNTS WHERE ACCOUNT_NUMBER = '982145001234'), SYSDATE-1, SYSDATE-1, 'CR', 450000, 'TXN-2026-901', 'Customer Wire - Invoice Settlement', 'Cognizant Solutions Pvt Ltd', 'CUSTOMER_RECEIPT', 'RECONCILED', SYSDATE FROM dual UNION ALL
    SELECT (SELECT ACCOUNT_ID FROM KF_BANK_ACCOUNTS WHERE ACCOUNT_NUMBER = '982145001234'), SYSDATE-2, SYSDATE-2, 'DR', 177000, 'TXN-2026-902', 'Vendor Disbursement - IT Services', 'Tata Consultancy Services', 'VENDOR_PAYMENT', 'RECONCILED', SYSDATE FROM dual UNION ALL
    SELECT (SELECT ACCOUNT_ID FROM KF_BANK_ACCOUNTS WHERE ACCOUNT_NUMBER = '412089005678'), SYSDATE-3, SYSDATE-3, 'CR', 350000, 'TXN-2026-903', 'Customer Wire - Cloud Project', 'Tech Mahindra Global Services', 'CUSTOMER_RECEIPT', 'RECONCILED', SYSDATE FROM dual UNION ALL
    SELECT (SELECT ACCOUNT_ID FROM KF_BANK_ACCOUNTS WHERE ACCOUNT_NUMBER = '412089005678'), SYSDATE-4, SYSDATE-4, 'DR', 236000, 'TXN-2026-904', 'Vendor Disbursement - Consulting', 'Infosys Ltd', 'VENDOR_PAYMENT', 'RECONCILED', SYSDATE FROM dual UNION ALL
    SELECT (SELECT ACCOUNT_ID FROM KF_BANK_ACCOUNTS WHERE ACCOUNT_NUMBER = '105432007890'), SYSDATE-7, SYSDATE-7, 'DR', 520000, 'TXN-2026-905', 'Advance Corporate Tax Q2', 'Income Tax Dept - Challan 280', 'TAX_PAYMENT', 'RECONCILED', SYSDATE FROM dual
    ]';

    COMMIT;
END;
