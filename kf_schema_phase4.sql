CREATE OR REPLACE PACKAGE BODY KF_PKG_FISCAL_YEAR AS
    FUNCTION GET_CURRENT_FISCAL_YEAR RETURN NUMBER IS
        v_id NUMBER;
    BEGIN
        -- Assuming FY runs Apr 1 to Mar 31
        SELECT FISCAL_YEAR_ID INTO v_id
        FROM KF_FISCAL_YEARS
        WHERE SYSDATE BETWEEN START_DATE AND END_DATE
        AND STATUS = 'ACTIVE';
        RETURN v_id;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN NULL;
    END GET_CURRENT_FISCAL_YEAR;

    FUNCTION IS_DATE_IN_FISCAL_YEAR (P_DATE IN DATE, P_FISCAL_YEAR_ID IN NUMBER) RETURN BOOLEAN IS
        v_start DATE;
        v_end DATE;
    BEGIN
        SELECT START_DATE, END_DATE INTO v_start, v_end 
        FROM KF_FISCAL_YEARS WHERE FISCAL_YEAR_ID = P_FISCAL_YEAR_ID;
        
        RETURN P_DATE BETWEEN v_start AND v_end;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN FALSE;
    END IS_DATE_IN_FISCAL_YEAR;
END KF_PKG_FISCAL_YEAR;
/

CREATE OR REPLACE PACKAGE BODY KF_PKG_INVOICE AS
    PROCEDURE VALIDATE_INVOICE (P_INVOICE_ID IN NUMBER) IS
        v_inv KF_INVOICES%ROWTYPE;
        v_vendor_status VARCHAR2(20);
        v_dup_count NUMBER;
    BEGIN
        SELECT * INTO v_inv FROM KF_INVOICES WHERE INVOICE_ID = P_INVOICE_ID;
        
        IF v_inv.INVOICE_DATE > v_inv.DUE_DATE THEN
            RAISE_APPLICATION_ERROR(-20001, 'Due date cannot be before invoice date.');
        END IF;

        IF v_inv.SUBTOTAL < 0 OR v_inv.TAX_AMOUNT < 0 OR v_inv.TDS_AMOUNT < 0 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Monetary values cannot be negative.');
        END IF;
        
        IF v_inv.TOTAL_AMOUNT <= 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Total amount must be greater than zero.');
        END IF;

        IF v_inv.TOTAL_AMOUNT != (v_inv.SUBTOTAL + v_inv.TAX_AMOUNT - v_inv.TDS_AMOUNT) THEN
            RAISE_APPLICATION_ERROR(-20004, 'Invoice total does not match Subtotal + Tax - TDS.');
        END IF;

        SELECT STATUS INTO v_vendor_status FROM KF_VENDORS WHERE VENDOR_ID = v_inv.VENDOR_ID;
        IF v_vendor_status != 'ACTIVE' THEN
            RAISE_APPLICATION_ERROR(-20005, 'Vendor is not active.');
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20006, 'Invoice or Vendor not found.');
    END VALIDATE_INVOICE;

    PROCEDURE UPDATE_STATUS (P_INVOICE_ID IN NUMBER, P_NEW_STATUS IN VARCHAR2) IS
    BEGIN
        IF P_NEW_STATUS NOT IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'PARTIALLY_PAID', 'PAID', 'OVERDUE', 'CANCELLED') THEN
            RAISE_APPLICATION_ERROR(-20010, 'Invalid invoice status: ' || P_NEW_STATUS);
        END IF;
        UPDATE KF_INVOICES SET STATUS = P_NEW_STATUS, UPDATED_DATE = SYSTIMESTAMP WHERE INVOICE_ID = P_INVOICE_ID;
    END UPDATE_STATUS;

    PROCEDURE SUBMIT_FOR_APPROVAL (P_INVOICE_ID IN NUMBER, P_REQUESTED_BY_USER_ID IN NUMBER) IS
        v_status VARCHAR2(50);
        v_username VARCHAR2(100);
    BEGIN
        SELECT STATUS INTO v_status FROM KF_INVOICES WHERE INVOICE_ID = P_INVOICE_ID FOR UPDATE;
        
        IF v_status != 'DRAFT' AND v_status != 'REJECTED' THEN
            RAISE_APPLICATION_ERROR(-20011, 'Only DRAFT or REJECTED invoices can be submitted.');
        END IF;

        VALIDATE_INVOICE(P_INVOICE_ID);
        
        SELECT USERNAME INTO v_username FROM KF_USERS WHERE USER_ID = P_REQUESTED_BY_USER_ID;

        UPDATE_STATUS(P_INVOICE_ID, 'PENDING_APPROVAL');
        
        KF_PKG_APPROVAL.SUBMIT_APPROVAL(
            P_ENTITY_TYPE => 'INVOICE',
            P_ENTITY_ID => P_INVOICE_ID,
            P_REQUESTED_BY => v_username
        );
        
        KF_PKG_AUDIT.LOG_EVENT(P_REQUESTED_BY_USER_ID, 'UPDATE', 'KF_INVOICES', TO_CHAR(P_INVOICE_ID));
    END SUBMIT_FOR_APPROVAL;
END KF_PKG_INVOICE;
/

CREATE OR REPLACE PACKAGE BODY KF_PKG_APPROVAL AS
    PROCEDURE VALIDATE_ENTITY (P_ENTITY_TYPE IN VARCHAR2, P_ENTITY_ID IN NUMBER) IS
        v_count NUMBER;
    BEGIN
        IF P_ENTITY_TYPE = 'INVOICE' THEN
            SELECT COUNT(*) INTO v_count FROM KF_INVOICES WHERE INVOICE_ID = P_ENTITY_ID;
        ELSIF P_ENTITY_TYPE = 'CASH_FLOW' THEN
            SELECT COUNT(*) INTO v_count FROM KF_CASH_FLOW_TRACKERS WHERE TRACKER_ID = P_ENTITY_ID;
        ELSE
            RAISE_APPLICATION_ERROR(-20020, 'Invalid entity type for approval.');
        END IF;
        
        IF v_count = 0 THEN
            RAISE_APPLICATION_ERROR(-20021, 'Entity ID does not exist for the given Entity Type.');
        END IF;
    END VALIDATE_ENTITY;

    PROCEDURE SUBMIT_APPROVAL (
        P_ENTITY_TYPE IN VARCHAR2, 
        P_ENTITY_ID IN NUMBER, 
        P_REQUESTED_BY IN VARCHAR2,
        P_ASSIGNED_APPROVER IN VARCHAR2 DEFAULT NULL
    ) IS
    BEGIN
        VALIDATE_ENTITY(P_ENTITY_TYPE, P_ENTITY_ID);
        INSERT INTO KF_APPROVAL_REQUESTS (ENTITY_TYPE, ENTITY_ID, REQUESTED_BY, ASSIGNED_APPROVER)
        VALUES (P_ENTITY_TYPE, P_ENTITY_ID, P_REQUESTED_BY, P_ASSIGNED_APPROVER);
    END SUBMIT_APPROVAL;

    PROCEDURE APPROVE (P_APPROVAL_ID IN NUMBER, P_DECISION_BY IN VARCHAR2, P_COMMENTS IN VARCHAR2 DEFAULT NULL) IS
        v_req KF_APPROVAL_REQUESTS%ROWTYPE;
    BEGIN
        SELECT * INTO v_req FROM KF_APPROVAL_REQUESTS WHERE APPROVAL_ID = P_APPROVAL_ID FOR UPDATE;
        
        IF v_req.STATUS != 'PENDING' THEN
            RAISE_APPLICATION_ERROR(-20022, 'Only pending requests can be approved.');
        END IF;

        UPDATE KF_APPROVAL_REQUESTS SET STATUS = 'APPROVED', DECISION_DATE = SYSTIMESTAMP WHERE APPROVAL_ID = P_APPROVAL_ID;
        
        INSERT INTO KF_APPROVAL_HISTORY (APPROVAL_ID, DECISION_BY, DECISION, COMMENTS)
        VALUES (P_APPROVAL_ID, P_DECISION_BY, 'APPROVED', P_COMMENTS);
        
        IF v_req.ENTITY_TYPE = 'INVOICE' THEN
            KF_PKG_INVOICE.UPDATE_STATUS(v_req.ENTITY_ID, 'APPROVED');
        ELSIF v_req.ENTITY_TYPE = 'CASH_FLOW' THEN
            UPDATE KF_CASH_FLOW_TRACKERS SET STATUS = 'APPROVED', APPROVED_BY = P_DECISION_BY, APPROVED_DATE = SYSTIMESTAMP WHERE TRACKER_ID = v_req.ENTITY_ID;
        END IF;
    END APPROVE;

    PROCEDURE REJECT (P_APPROVAL_ID IN NUMBER, P_DECISION_BY IN VARCHAR2, P_COMMENTS IN VARCHAR2) IS
        v_req KF_APPROVAL_REQUESTS%ROWTYPE;
    BEGIN
        IF P_COMMENTS IS NULL THEN
            RAISE_APPLICATION_ERROR(-20023, 'Rejection reason is required.');
        END IF;
        
        SELECT * INTO v_req FROM KF_APPROVAL_REQUESTS WHERE APPROVAL_ID = P_APPROVAL_ID FOR UPDATE;
        
        IF v_req.STATUS != 'PENDING' THEN
            RAISE_APPLICATION_ERROR(-20024, 'Only pending requests can be rejected.');
        END IF;

        UPDATE KF_APPROVAL_REQUESTS SET STATUS = 'REJECTED', DECISION_DATE = SYSTIMESTAMP, COMMENTS = P_COMMENTS WHERE APPROVAL_ID = P_APPROVAL_ID;
        
        INSERT INTO KF_APPROVAL_HISTORY (APPROVAL_ID, DECISION_BY, DECISION, COMMENTS)
        VALUES (P_APPROVAL_ID, P_DECISION_BY, 'REJECTED', P_COMMENTS);
        
        IF v_req.ENTITY_TYPE = 'INVOICE' THEN
            KF_PKG_INVOICE.UPDATE_STATUS(v_req.ENTITY_ID, 'REJECTED');
        ELSIF v_req.ENTITY_TYPE = 'CASH_FLOW' THEN
            UPDATE KF_CASH_FLOW_TRACKERS SET STATUS = 'REJECTED' WHERE TRACKER_ID = v_req.ENTITY_ID;
        END IF;
    END REJECT;
END KF_PKG_APPROVAL;
/

CREATE OR REPLACE PACKAGE BODY KF_PKG_PAYMENT AS
    PROCEDURE CREATE_PAYMENT (
        P_INVOICE_ID IN NUMBER,
        P_PAYMENT_AMOUNT IN NUMBER,
        P_PAYMENT_METHOD IN VARCHAR2,
        P_REFERENCE_NUMBER IN VARCHAR2,
        P_CREATED_BY_USER_ID IN NUMBER
    ) IS
        v_inv KF_INVOICES%ROWTYPE;
        v_paid NUMBER := 0;
        v_outstanding NUMBER := 0;
    BEGIN
        IF P_PAYMENT_AMOUNT <= 0 THEN
            RAISE_APPLICATION_ERROR(-20030, 'Payment amount must be greater than zero.');
        END IF;

        SELECT * INTO v_inv FROM KF_INVOICES WHERE INVOICE_ID = P_INVOICE_ID FOR UPDATE;
        
        IF v_inv.STATUS NOT IN ('APPROVED', 'PARTIALLY_PAID') THEN
            RAISE_APPLICATION_ERROR(-20031, 'Payments can only be applied to APPROVED or PARTIALLY_PAID invoices.');
        END IF;

        SELECT NVL(SUM(PAYMENT_AMOUNT), 0) INTO v_paid FROM KF_PAYMENTS WHERE INVOICE_ID = P_INVOICE_ID AND STATUS = 'COMPLETED';
        v_outstanding := v_inv.TOTAL_AMOUNT - v_paid;
        
        IF P_PAYMENT_AMOUNT > v_outstanding THEN
            RAISE_APPLICATION_ERROR(-20032, 'Payment amount exceeds outstanding balance.');
        END IF;

        INSERT INTO KF_PAYMENTS (INVOICE_ID, VENDOR_ID, PAYMENT_DATE, PAYMENT_AMOUNT, PAYMENT_METHOD, REFERENCE_NUMBER, STATUS)
        VALUES (P_INVOICE_ID, v_inv.VENDOR_ID, SYSDATE, P_PAYMENT_AMOUNT, P_PAYMENT_METHOD, P_REFERENCE_NUMBER, 'COMPLETED');

        -- Update status
        IF (v_paid + P_PAYMENT_AMOUNT) >= v_inv.TOTAL_AMOUNT THEN
            KF_PKG_INVOICE.UPDATE_STATUS(P_INVOICE_ID, 'PAID');
        ELSE
            KF_PKG_INVOICE.UPDATE_STATUS(P_INVOICE_ID, 'PARTIALLY_PAID');
        END IF;

        KF_PKG_AUDIT.LOG_EVENT(P_CREATED_BY_USER_ID, 'INSERT', 'KF_PAYMENTS', TO_CHAR(P_INVOICE_ID));
    END CREATE_PAYMENT;
END KF_PKG_PAYMENT;
/

CREATE OR REPLACE PACKAGE BODY KF_PKG_TDS AS
    FUNCTION CALCULATE_TDS (P_TAXABLE_AMOUNT IN NUMBER, P_TDS_RATE IN NUMBER) RETURN NUMBER IS
    BEGIN
        IF P_TDS_RATE < 0 OR P_TDS_RATE > 100 THEN
            RAISE_APPLICATION_ERROR(-20040, 'TDS Rate must be between 0 and 100.');
        END IF;
        RETURN (P_TAXABLE_AMOUNT * P_TDS_RATE) / 100;
    END CALCULATE_TDS;

    PROCEDURE CREATE_TDS_TRANSACTION (
        P_INVOICE_ID IN NUMBER,
        P_TDS_SECTION IN VARCHAR2,
        P_TDS_RATE IN NUMBER,
        P_CREATED_BY_USER_ID IN NUMBER
    ) IS
        v_inv KF_INVOICES%ROWTYPE;
        v_taxable NUMBER;
        v_tds NUMBER;
    BEGIN
        SELECT * INTO v_inv FROM KF_INVOICES WHERE INVOICE_ID = P_INVOICE_ID;
        v_taxable := v_inv.SUBTOTAL; -- Simplified assumption for taxable base
        v_tds := CALCULATE_TDS(v_taxable, P_TDS_RATE);
        
        INSERT INTO KF_TDS_TRANSACTIONS (INVOICE_ID, VENDOR_ID, TDS_SECTION, TDS_RATE, TAXABLE_AMOUNT, TDS_AMOUNT, DEDUCTION_DATE, STATUS)
        VALUES (P_INVOICE_ID, v_inv.VENDOR_ID, P_TDS_SECTION, P_TDS_RATE, v_taxable, v_tds, SYSDATE, 'PENDING');
        
        KF_PKG_AUDIT.LOG_EVENT(P_CREATED_BY_USER_ID, 'INSERT', 'KF_TDS_TRANSACTIONS', TO_CHAR(P_INVOICE_ID));
    END CREATE_TDS_TRANSACTION;
END KF_PKG_TDS;
