-- Kovaion Finance - Master Database Schema
-- Clean & Repeatable Installation Script for Oracle APEX
--------------------------------------------------------

-- Clean up existing tables safely before recreation
BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables 
        WHERE table_name IN (
            'KF_IMPORT_ERRORS', 
            'KF_PIPELINE_COLUMNS', 
            'KF_UPLOAD_TRACKER', 
            'KF_CASHFLOW_LEDGER', 
            'KF_EMAIL_DOCUMENTS', 
            'KF_AUDIT_LOGS', 
            'KF_INVOICES', 
            'KF_VENDORS'
        )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- 1. Vendors Master
CREATE TABLE KF_VENDORS (
    VENDOR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VENDOR_NAME VARCHAR2(150) NOT NULL,
    PAN VARCHAR2(20),
    STATE VARCHAR2(50),
    GSTIN VARCHAR2(20)
);

-- 2. Invoices Table
CREATE TABLE KF_INVOICES (
    INVOICE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_NUMBER VARCHAR2(50) NOT NULL,
    VENDOR_ID NUMBER REFERENCES KF_VENDORS(VENDOR_ID),
    INVOICE_DATE DATE,
    DUE_DATE DATE,
    INVOICE_PERIOD VARCHAR2(20),
    NATURE_OF_EXPENSE VARCHAR2(100),
    TAXABLE_VALUE NUMBER,
    GST_AMOUNT NUMBER,
    TOTAL_AMOUNT NUMBER,
    TDS_SECTION VARCHAR2(20),
    TDS_RATE NUMBER,
    STATUS VARCHAR2(30) DEFAULT 'Pending',
    SECTION_NAME VARCHAR2(50),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- 3. Audit Logs
CREATE TABLE KF_AUDIT_LOGS (
    LOG_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DB_USER VARCHAR2(100),
    ACTION_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP,
    INVOICE_NUMBER VARCHAR2(50),
    VENDOR_NAME VARCHAR2(150),
    ACTION_TYPE VARCHAR2(50),
    FIELD_CHANGED VARCHAR2(50),
    OLD_VALUE VARCHAR2(4000),
    NEW_VALUE VARCHAR2(4000)
);

-- 4. Email & Documents Inbox
CREATE TABLE KF_EMAIL_DOCUMENTS (
    DOCUMENT_ID VARCHAR2(50) PRIMARY KEY,
    EMAIL_SUBJECT VARCHAR2(255),
    SENDER VARCHAR2(150),
    RECEIVED_DATE TIMESTAMP,
    ATTACHMENT_NAME VARCHAR2(150),
    VENDOR_NAME VARCHAR2(150),
    TOTAL_INVOICE_VALUE NUMBER,
    NET_PAYABLE NUMBER,
    STATUS VARCHAR2(30) DEFAULT 'Pending Review'
);

-- 5. Cash Flow Ledger (Matrix)
CREATE TABLE KF_CASHFLOW_LEDGER (
    LEDGER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIN_YEAR VARCHAR2(20),
    REPORT_MONTH VARCHAR2(10),
    SECTION_HEADING VARCHAR2(50), -- 'CASH_RECEIPTS' or 'CASH_PAYMENTS'
    LINE_ITEM VARCHAR2(100),
    AMOUNT NUMBER
);

-- 6. Upload Tracker & Pipeline
CREATE TABLE KF_UPLOAD_TRACKER (
    UPLOAD_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILE_NAME VARCHAR2(150),
    REPORTING_PERIOD VARCHAR2(20),
    CURRENCY VARCHAR2(10),
    COMPANY_ENTITY VARCHAR2(100),
    STATUS VARCHAR2(30),
    RECORDS_COUNT NUMBER,
    VALID_COUNT NUMBER,
    ERROR_COUNT NUMBER,
    UPLOADED_BY VARCHAR2(100),
    UPLOAD_TIMESTAMP TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE KF_PIPELINE_COLUMNS (
    MAP_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCE_COLUMN VARCHAR2(100),
    MAPPED_TO VARCHAR2(100),
    CONFIDENCE_PERCENT NUMBER,
    ACTION_STATUS VARCHAR2(50)
);

CREATE TABLE KF_IMPORT_ERRORS (
    ERROR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILE_NAME VARCHAR2(255),
    LINE_NUMBER NUMBER,
    ERROR_MESSAGE VARCHAR2(4000),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

