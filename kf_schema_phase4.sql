CREATE OR REPLACE PACKAGE BODY KF_PKG_AUDIT AS
    PROCEDURE LOG_EVENT (
        P_USER_ID IN NUMBER,
        P_ACTION IN VARCHAR2,
        P_TABLE_NAME IN VARCHAR2,
        P_RECORD_ID IN VARCHAR2,
        P_OLD_VALUE IN CLOB DEFAULT NULL,
        P_NEW_VALUE IN CLOB DEFAULT NULL
    ) IS
        V_APEX_USER VARCHAR2(255);
        V_SESSION_ID VARCHAR2(255);
    BEGIN
        -- Safely get APEX context if it exists
        V_APEX_USER := SYS_CONTEXT('APEX$SESSION', 'APP_USER');
        
        BEGIN
            V_SESSION_ID := V('APP_SESSION');
        EXCEPTION WHEN OTHERS THEN
            V_SESSION_ID := NULL;
        END;

        INSERT INTO KF_AUDIT_LOG (
            USER_ID, APEX_SESSION_USER, ACTION, TABLE_NAME, RECORD_ID, 
            OLD_VALUE, NEW_VALUE, IP_ADDRESS, SESSION_ID
        ) VALUES (
            P_USER_ID, V_APEX_USER, P_ACTION, P_TABLE_NAME, P_RECORD_ID, 
            P_OLD_VALUE, P_NEW_VALUE, SYS_CONTEXT('USERENV', 'IP_ADDRESS'), V_SESSION_ID
        );
        -- Notice: No COMMIT here. The caller transaction controls the commit.
    END LOG_EVENT;
END KF_PKG_AUDIT;
/

CREATE OR REPLACE PACKAGE BODY KF_PKG_NOTIFICATION AS
    PROCEDURE CREATE_NOTIFICATION (
        P_USER_ID IN NUMBER,
        P_TITLE IN VARCHAR2,
        P_MESSAGE IN VARCHAR2,
        P_TYPE IN VARCHAR2 DEFAULT 'INFO',
        P_RELATED_ENTITY_TYPE IN VARCHAR2 DEFAULT NULL,
        P_RELATED_ENTITY_ID IN NUMBER DEFAULT NULL
    ) IS
    BEGIN
        INSERT INTO KF_NOTIFICATIONS (
            USER_ID, TYPE, TITLE, MESSAGE, REFERENCE_ENTITY, REFERENCE_ID
        ) VALUES (
            P_USER_ID, P_TYPE, P_TITLE, P_MESSAGE, P_RELATED_ENTITY_TYPE, P_RELATED_ENTITY_ID
        );
    END CREATE_NOTIFICATION;

    PROCEDURE MARK_AS_READ (P_NOTIFICATION_ID IN NUMBER) IS
    BEGIN
        UPDATE KF_NOTIFICATIONS 
        SET IS_READ = 'Y', READ_DATE = SYSTIMESTAMP 
        WHERE NOTIFICATION_ID = P_NOTIFICATION_ID;
    END MARK_AS_READ;

    PROCEDURE MARK_ALL_AS_READ (P_USER_ID IN NUMBER) IS
    BEGIN
        UPDATE KF_NOTIFICATIONS 
        SET IS_READ = 'Y', READ_DATE = SYSTIMESTAMP 
        WHERE USER_ID = P_USER_ID AND IS_READ = 'N';
    END MARK_ALL_AS_READ;
END KF_PKG_NOTIFICATION;
